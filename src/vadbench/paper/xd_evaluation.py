"""Frozen XD RGB evaluation on independently sealed canonical prefix coordinates.

No annotation-driven choice or resampling occurs here. Raw-coordinate receipts
must be externally sealed before this entry is called; this module cannot create
one. In particular the historical feature-header freeze alone cannot open the
gate. The metric uses raw frame predictions, not reconstructed I3D row scores.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from vadbench.data.manifest import DatasetSplit, load_manifest_jsonl
from vadbench.engine.coverage import validate_frame_coverage
from vadbench.paper import evaluation as shared
from vadbench.research.xd_feature_grid import (
    OFFICIAL_GT_LENGTH,
    OFFICIAL_VIDEO_COUNT,
    _verified_rows,
    precision_recall_trapezoid_auc,
)

PROTOCOL_ID = "xd-violence/frozen-rgb-raw-prefix-pr-auc-v1"
CANONICAL_METADATA_SHA256 = "a03cdc6860326d52d0a767d4784e73e7f7c72a9b38cd2017a9c23ed3263537ce"
GT_FILE_SHA256 = "e2f9260882450e9ccabe8deaaac63a54b94558db4197f3e329125bf36e3b3863"
SCOPE_FILE_SHA256 = "82ee139fcc21b45bb4df1236267794f2ae48ea85ab9d70c8e177d31e0a922f7b"
METHOD_FREEZE_CANONICAL_SHA256 = "54b81894e42e244c320b5d40a06c21199e3e77ebf1e53264b0f6069bda005271"
MAPPING = {
    "index_base": 0,
    "end_policy": "half_open",
    "prefix_origin": 0,
    "length": "16*Ti",
    "prediction_overlap_reduction": "mean",
}


def _bound(path: str | Path, expected: str, name: str) -> Path:
    result = Path(path).expanduser().resolve()
    if not expected or shared._digest(result, name=name) != expected:
        raise ValueError(f"{name} SHA-256 differs from its external seal")
    return result


def _scope(path: str | Path) -> dict[str, Any]:
    return shared._json(_bound(path, SCOPE_FILE_SHA256, "XD scope"), name="XD scope")


@dataclass(frozen=True, kw_only=True)
class FrozenXDEvaluationRequest(shared.FrozenEvaluationRequest):
    """audit_report is the sealed raw-coordinate receipt, never a UCF audit."""

    canonical_metadata: str
    ground_truth: str
    raw_coordinate_receipt_sha256: str
    head_data_contract_sha256: str
    original_role_lock_path: str
    scope_path: str = "projects/icassp2027/decisions/xd-validation-scope-v1.json"

    def __post_init__(self) -> None:
        super().__post_init__()
        if self.encoder not in {"videomaev2", "timesformer"}:
            raise ValueError("XD frozen scope permits only videomaev2 and timesformer")


@dataclass(frozen=True)
class SealedXDCoordinates:
    manifest: tuple[Any, ...]
    grid_rows: Sequence[Mapping[str, Any]]
    raw_rows: Sequence[Mapping[str, Any]]
    input_hashes: Mapping[Path, str]

    def verify_unchanged(self) -> None:
        for path, digest in self.input_hashes.items():
            _bound(path, digest, "sealed XD input")


def verify_raw_coordinates(request: FrozenXDEvaluationRequest) -> SealedXDCoordinates:
    """Fail closed before loading any model, checkpoint or GT array values.

    The v1 receipt binds the manifest, full raw bytes, canonical grid, and three
    separately SHA-bound dataset-only audit reports (alignment, raw timing,
    prespecified suffix). Reports must explicitly attest completed/passed, no
    model scores, and every one of the 800 video identities. No receipt is
    generated by the evaluator, and pending reports are never accepted.
    """
    receipt_path = _bound(
        request.audit_report, request.raw_coordinate_receipt_sha256, "raw-coordinate receipt"
    )
    receipt = shared._json(receipt_path, name="raw-coordinate receipt")
    if (
        receipt.get("schema_version") != 1
        or receipt.get("status") != "sealed"
        or receipt.get("protocol") != PROTOCOL_ID
        or receipt.get("mapping") != MAPPING
        or receipt.get("canonical_metadata_sha256") != CANONICAL_METADATA_SHA256
        or receipt.get("gt_file_sha256") != GT_FILE_SHA256
    ):
        raise ValueError(
            "XD raw-coordinate receipt is pending or has an unsupported coordinate contract"
        )
    manifest_path = _bound(
        request.test_manifest, receipt.get("test_manifest_sha256"), "XD test manifest"
    )
    metadata_path = Path(request.canonical_metadata).resolve()
    metadata = shared._json(metadata_path, name="XD canonical metadata")
    grid, _ = _verified_rows(metadata, CANONICAL_METADATA_SHA256)
    manifest = load_manifest_jsonl(manifest_path)
    rows = receipt.get("records")
    if (
        len(manifest) != OFFICIAL_VIDEO_COUNT
        or not isinstance(rows, list)
        or len(rows) != OFFICIAL_VIDEO_COUNT
        or any(r.split != DatasetSplit.TEST for r in manifest)
    ):
        raise ValueError("XD evaluation requires the complete sealed 800-video test cohort")
    by_id = {r.video_id: r for r in manifest}
    if len(by_id) != OFFICIAL_VIDEO_COUNT or {r.get("video_id") for r in rows} != set(by_id):
        raise ValueError("raw-coordinate receipt has duplicate, missing or foreign test identities")
    hashes = {
        receipt_path: request.raw_coordinate_receipt_sha256,
        manifest_path: receipt["test_manifest_sha256"],
        metadata_path: shared._digest(metadata_path, name="XD metadata"),
    }
    audits = shared._mapping(receipt.get("audits"), "raw-coordinate receipt.audits")
    audit_documents = {}
    for name in ("annotation_alignment", "raw_timing", "prespecified_suffix"):
        entry = shared._mapping(audits.get(name), f"XD {name} audit")
        path = _bound(receipt_path.parent / entry["path"], entry.get("sha256"), name)
        audit = shared._json(path, name=name)
        if (
            audit.get("status") != "passed"
            or audit.get("model_scores_read") is not False
            or audit.get("video_count") != OFFICIAL_VIDEO_COUNT
            or audit.get("test_manifest_sha256") != receipt["test_manifest_sha256"]
            or audit.get("canonical_metadata_sha256") != CANONICAL_METADATA_SHA256
        ):
            raise ValueError(f"XD {name} audit is incomplete or not bound to the sealed cohort")
        if name == "prespecified_suffix":
            plan = shared._mapping(audit.get("preregistration"), "suffix preregistration")
            plan_path = _bound(
                path.parent / plan["path"], plan.get("sha256"), "suffix preregistration"
            )
            hashes[plan_path] = plan["sha256"]
            from vadbench.research.xd_raw_alignment import fixed_candidates

            registration = shared._json(plan_path, name="suffix preregistration")
            if (
                registration.get("candidates") != fixed_candidates()
                or registration.get("canonical_metadata_sha256") != CANONICAL_METADATA_SHA256
                or registration.get("expected_gt_sha256") != GT_FILE_SHA256
            ):
                raise ValueError(
                    "XD suffix preregistration differs from the fixed coordinate audit"
                )
        candidate_path = _bound(
            receipt_path.parent / "candidate-results.json",
            audit.get("candidate_results_sha256"),
            "XD computed candidate results",
        )
        hashes[candidate_path] = audit["candidate_results_sha256"]
        for source_path, digest in shared._mapping(
            audit.get("source_sha256"), "XD audit source hashes"
        ).items():
            if source_path in {"gt.npy", "annotations.txt"}:
                continue  # These aliases also occur as SHA-bound absolute paths.
            bound = _bound(source_path, digest, "XD audit source")
            hashes[bound] = digest
        audit_documents[name] = audit
        hashes[path] = entry["sha256"]
    candidate = shared._json(
        receipt_path.parent / "candidate-results.json", name="XD computed candidate results"
    )
    if (
        candidate.get("status") != "sealed"
        or candidate.get("video_count") != OFFICIAL_VIDEO_COUNT
        or candidate.get("prefix_exact_all") is not True
        or candidate.get("suffix_resolved_without_coordinate_ambiguity") is not True
        or candidate.get("exact_but_distinct_coordinate_candidates") != []
    ):
        raise ValueError("XD computed mapping audit does not establish the sealed prefix")
    timing_audit = audit_documents["raw_timing"]
    timing_hashes = shared._mapping(
        timing_audit.get("probe_receipt_sha256"), "XD timing probe receipts"
    )
    expected_probe_paths = {
        f"private/probes/{i:04d}/receipt.json" for i in range(OFFICIAL_VIDEO_COUNT)
    }
    if set(timing_hashes) != expected_probe_paths:
        raise ValueError("XD timing proof does not cover the complete sealed cohort")
    runtime_path = _bound(
        receipt_path.parent / "runtime.json", timing_audit.get("runtime_sha256"), "XD audit runtime"
    )
    hashes[runtime_path] = timing_audit["runtime_sha256"]
    for index, (raw, feature) in enumerate(zip(rows, grid, strict=True)):
        record = by_id[raw["video_id"]]
        length = feature["t"] * 16
        if (
            raw.get("video_index") != index
            or raw.get("feature_name") != feature["feature_name"]
            or Path(record.path).stem + "__0.npy" != feature["feature_name"]
            or raw.get("path") != record.path
            or raw.get("num_frames") != record.num_frames
            or type(raw.get("num_frames")) is not int
            or record.num_frames < length
            or raw.get("fps") != record.fps
            or record.fps != 24.0
            or raw.get("pts_verified") is not True
            or raw.get("suffix_audit_passed") is not True
        ):
            raise ValueError(
                f"XD raw coordinate/FPS/PTS/suffix mismatch at canonical video {index}"
            )
        raw_path = _bound(
            record.resolve_path(request.dataset_root), raw.get("raw_sha256"), "XD raw video"
        )
        hashes[raw_path] = raw["raw_sha256"]
        if raw_path.stat().st_size != raw.get("raw_bytes"):
            raise ValueError("XD raw video byte size differs from the coordinate receipt")
        probe_name = f"private/probes/{index:04d}/receipt.json"
        probe_path = _bound(
            receipt_path.parent / probe_name, timing_hashes[probe_name], "XD timing probe"
        )
        hashes[probe_path] = timing_hashes[probe_name]
        probe = shared._json(probe_path, name="XD timing probe")
        if any(
            probe.get(key) != raw.get(key)
            for key in (
                "video_index",
                "video_id",
                "feature_name",
                "path",
                "raw_sha256",
                "raw_bytes",
            )
        ):
            raise ValueError("XD timing probe identity differs from the sealed raw video")
        artifacts = shared._mapping(probe.get("artifact_sha256"), "XD timing probe artifacts")
        if set(artifacts) != {"ffprobe.json", "ffprobe.stderr.txt", "opencv.json"}:
            raise ValueError("XD timing probe lacks its complete raw observation artifacts")
        for name, digest in artifacts.items():
            path = _bound(probe_path.parent / name, digest, "XD timing observation")
            hashes[path] = digest
        stderr = (probe_path.parent / "ffprobe.stderr.txt").read_bytes()
        from vadbench.research.xd_raw_alignment import _accepted_ffprobe_stderr, validate_timing

        stderr_classification = _accepted_ffprobe_stderr(0, stderr)
        if stderr_classification is None:
            raise ValueError("XD timing probe contains FFprobe decode errors")
        declared_classification = probe.get("ffprobe_stderr_classification")
        if stderr_classification == "none":
            if declared_classification not in (None, "none"):
                raise ValueError("XD timing probe stderr classification differs from its artifact")
        elif declared_classification != stderr_classification:
            raise ValueError("XD timing probe stderr classification differs from its artifact")

        computed = validate_timing(
            shared._json(probe_path.parent / "ffprobe.json", name="XD full frame PTS"),
            shared._json(probe_path.parent / "opencv.json", name="XD full OpenCV decode"),
        )
        if any(probe.get(key) != value or raw.get(key) != value for key, value in computed.items()):
            raise ValueError("XD sealed timing differs from its recomputed full-frame evidence")
    return SealedXDCoordinates(manifest, grid, rows, hashes)


def validate_xd_data_content_evidence(
    evidence: Mapping[str, Any], coordinates: SealedXDCoordinates
) -> None:
    """Bind actual extraction content evidence to the sealed raw-video bytes."""
    from vadbench.data.audit import compute_manifest_sha256
    from vadbench.features import compute_encoder_fingerprint

    videos = evidence.get("videos")
    if not isinstance(videos, list) or len(videos) != len(coordinates.raw_rows):
        raise ValueError("XD extracted data evidence lacks the complete sealed cohort")
    expected = {r["video_id"]: (r["raw_sha256"], r["raw_bytes"]) for r in coordinates.raw_rows}
    observed = {r["video_id"]: (r.get("sha256"), r.get("size_bytes")) for r in videos}
    if observed != expected or len(observed) != len(videos):
        raise ValueError("XD extracted video SHA/bytes differ from the raw-coordinate seal")
    if evidence.get("canonical_manifest_sha256") != "sha256:" + compute_manifest_sha256(
        coordinates.manifest
    ):
        raise ValueError("XD extracted manifest differs from the sealed raw-coordinate manifest")
    if evidence.get("source_digest") != compute_encoder_fingerprint(
        {"canonical_manifest": evidence["canonical_manifest_sha256"], "video_contents": videos}
    ):
        raise ValueError("XD extracted content fingerprint is not self-consistent")


def score_xd_predictions(
    records: Sequence[Any], coordinates: SealedXDCoordinates, ground_truth_path: str | Path
) -> dict[str, Any]:
    """Score complete permit-produced frame intervals on the canonical prefix."""
    coordinates.verify_unchanged()
    truth_path = _bound(ground_truth_path, GT_FILE_SHA256, "canonical XD GT")
    by_id = {r.video_id: [] for r in coordinates.manifest}
    for record in records:
        if record.video_id not in by_id:
            raise ValueError("prediction contains a video outside the sealed XD cohort")
        by_id[record.video_id].append(record)
    manifest = {r.video_id: r for r in coordinates.manifest}
    arrays = []
    for raw, grid in zip(coordinates.raw_rows, coordinates.grid_rows, strict=True):
        video_id = raw["video_id"]
        items = sorted(by_id[video_id], key=lambda r: r.clip_index)
        record = manifest[video_id]
        validate_frame_coverage(
            video_id=video_id,
            clip_indices=np.asarray([r.clip_index for r in items]),
            frame_starts=np.asarray([r.frame_start for r in items]),
            frame_ends=np.asarray([r.frame_end for r in items]),
            num_frames=record.num_frames,
            fps=record.fps,
            require_fps=True,
            require_complete=True,
        )
        scores = np.empty(record.num_frames, dtype=np.float64)
        for item in items:
            if not np.isfinite(item.anomaly_score):
                raise ValueError("XD prediction contains a nonfinite score")
            scores[item.frame_start : item.frame_end] = item.anomaly_score
        arrays.append(scores[: grid["t"] * 16])
    # GT is first opened after every metadata and prediction-coverage gate passes.
    truth = np.load(truth_path, allow_pickle=False)
    if truth.shape != (OFFICIAL_GT_LENGTH,):
        raise ValueError("canonical XD GT shape differs from the frozen grid")
    result = {
        "protocol_id": PROTOCOL_ID,
        "frame_pr_auc": precision_recall_trapezoid_auc(truth, np.concatenate(arrays)),
        "video_count": len(arrays),
        "gt_length": OFFICIAL_GT_LENGTH,
        "metadata_sha256": CANONICAL_METADATA_SHA256,
        "gt_file_sha256": GT_FILE_SHA256,
        "mapping": MAPPING,
        "prediction_representation": "raw_frame_dense_overlap_mean",
        "scope": "RGB raw-frame predictions on canonical GT prefix; not I3D feature-row scores",
    }
    coordinates.verify_unchanged()
    _bound(truth_path, GT_FILE_SHA256, "canonical XD GT")
    return result


def load_frozen_xd_detector_source(
    path: str | Path,
    *,
    freeze: Mapping[str, Any],
    expected_encoder: str,
    role_lock_path: str | Path,
    head_data_contract_path: str | Path,
    source_manifest_root: str | Path,
    scope_path: str | Path,
    original_role_lock_path: str | Path,
    method_freeze_path: str | Path,
    head_data_contract_sha256: str,
) -> shared.FrozenDetectorSource:
    """Use the common checkpoint/QA/permit verifier with XD's fixed role plan."""
    scope = _scope(scope_path)
    if expected_encoder not in scope["secondary_encoders"]:
        raise ValueError("source encoder is outside the frozen XD scope")
    if shared._canonical_sha256(freeze) != METHOD_FREEZE_CANONICAL_SHA256:
        raise ValueError("XD evaluation requires the unchanged UCF method freeze")
    contract_path = _bound(head_data_contract_path, head_data_contract_sha256, "XD head contract")
    plan_path = _bound(
        role_lock_path, scope["derived_role_plan_file_sha256"], "XD derived role plan"
    )
    _bound(
        original_role_lock_path, scope["original_role_lock_file_sha256"], "XD original role lock"
    )

    def verify_roles(*, train_manifest, validation_manifest, **_):
        from vadbench.data.xd_materialization import validate_xd_head_data_contract

        verified = validate_xd_head_data_contract(
            contract_path,
            scope_path=scope_path,
            derived_plan_path=plan_path,
            original_lock_path=original_role_lock_path,
            method_freeze_path=method_freeze_path,
            source_root=source_manifest_root,
        )
        for role, actual_path in (("fit", train_manifest), ("select", validation_manifest)):
            if actual_path is None:
                raise ValueError(f"XD detector source lacks its complete frozen {role} manifest")
            actual = load_manifest_jsonl(actual_path)
            expected = verified["roles"][role]["controller_records"]

            def identity(record):
                document = record.to_dict()
                document.pop("duration_seconds", None)
                document["metadata"] = dict(record.metadata)
                document["metadata"].pop("video_probe", None)
                return document

            # enrich_video_info adds video_probe and reconciles duration. All
            # identity, label, frame-count/FPS and original provenance stay bound.
            if len(actual) != len(expected) or {r.video_id: identity(r) for r in actual} != {
                r.video_id: identity(r) for r in expected
            }:
                raise ValueError(
                    f"XD source {role} manifest differs from the fixed controller contract"
                )
            expected_by_id = {r.video_id: r for r in expected}
            if any(
                r.duration_seconds is None
                or expected_by_id[r.video_id].duration_seconds is None
                or abs(r.duration_seconds - expected_by_id[r.video_id].duration_seconds)
                > max(0.1, 1 / r.fps)
                for r in actual
            ):
                raise ValueError(
                    f"XD source {role} duration differs from its audited raw-video contract"
                )
        hashes = dict(verified["source_hashes"])
        for bound in (Path(original_role_lock_path), Path(scope_path), Path(method_freeze_path)):
            bound = bound.resolve()
            hashes[str(bound)] = shared._digest(bound, name="XD source input")
        return (
            plan_path,
            scope["derived_role_plan_file_sha256"],
            contract_path,
            head_data_contract_sha256,
            hashes,
        )

    source = shared._load_frozen_detector_source(
        path,
        freeze=freeze,
        expected_encoder=expected_encoder,
        role_lock_path=plan_path,
        head_data_contract_path=contract_path,
        source_manifest_root=source_manifest_root,
        verify_training_roles=verify_roles,
    )
    allowed_seeds = (
        scope["global_uniform_head_seeds"]
        if source.reducer["name"] == "global_uniform"
        else scope["head_seeds"]
    )
    if (
        source.reducer["name"] not in scope["methods"]
        or source.training_identity.seed not in allowed_seeds
    ):
        raise ValueError("XD source method/head seed is outside the frozen scope")
    return source


def run_frozen_xd_evaluation(
    request: FrozenXDEvaluationRequest, *, adapter_factory=None, video_backend=None
) -> shared.FrozenEvaluationResult:
    """Open the raw-coordinate gate, then reuse strict extraction and prediction."""
    _scope(request.scope_path)
    freeze, freeze_sha = shared._load_freeze(request.freeze_path)
    if shared._canonical_sha256(freeze) != METHOD_FREEZE_CANONICAL_SHA256:
        raise ValueError("XD evaluation requires the unchanged UCF method freeze")
    coordinates = verify_raw_coordinates(request)

    def source_loader(path, **kwargs):
        return load_frozen_xd_detector_source(
            path,
            **kwargs,
            scope_path=request.scope_path,
            original_role_lock_path=request.original_role_lock_path,
            method_freeze_path=request.freeze_path,
            head_data_contract_sha256=request.head_data_contract_sha256,
        )

    return shared._run_frozen_evaluation(
        request,
        freeze=freeze,
        freeze_sha=freeze_sha,
        test_manifest=Path(request.test_manifest).resolve(),
        audit_report=Path(request.audit_report).resolve(),
        manifest=coordinates.manifest,
        source_loader=source_loader,
        score=lambda records: score_xd_predictions(records, coordinates, request.ground_truth),
        protocol=PROTOCOL_ID,
        stage_name="frozen_xd_evaluation",
        adapter_factory=adapter_factory,
        video_backend=video_backend,
        extra_inputs={
            "xd_scope": request.scope_path,
            "xd_canonical_metadata": request.canonical_metadata,
            "xd_gt": request.ground_truth,
            "xd_original_role_lock": request.original_role_lock_path,
        },
        validate_extraction=lambda resolved: validate_xd_data_content_evidence(
            shared._mapping(resolved.get("data_content_evidence"), "XD extraction data evidence"),
            coordinates,
        ),
    )
